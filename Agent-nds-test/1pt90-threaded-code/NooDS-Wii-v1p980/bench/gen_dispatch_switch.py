out.append("static inline int switchDispatch(Ctx *c, uint32_t op) {")
out.append("    switch ((op >> 20) & 0xFF) {")
for hi in range(256):
    out.append("    case 0x%02X: switch ((op >> 4) & 0xF) {" % hi)
    for lo in range(16):
        idx = (hi << 4) | lo
        out.append("        case %d: return bh%d(c, op);" % (lo, idx % 8))
    out.append("        } return bh0(c, op);")
out.append("    }")
out.append("    return bh0(c, op);")
out.append("}")
