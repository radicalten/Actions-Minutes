// The game build: link the recompiled game to the runtime and start it.
//
// This is the file that turns "a .cia with a ROM on the SD card" into "the game runs". It is
// only compiled with GAME=1 (`make game`), because it needs the ROM-derived code:
//
//     tools/recompile.sh --rom baserom.z64     -> game/RecompiledFuncs/*.c, game/section_table.cpp
//     make game                                -> bin/racer3ds-game.cia
//
// Everything the runtime needs is a callback: which ROM, where the entrypoint is, how to
// draw, how to make sound, how to read the pad. The recompiled code itself is just C.
//
// The renderer here is a stub (`renderer_game.cpp`) that counts display lists and presents the
// VI buffer; it does NOT interpret RDP commands yet. Replacing that one file with
// rt64-3ds's renderer is what makes the picture appear; everything else in this file is final.
#include <3ds.h>
#include <cstdio>
#include <cstring>
#include <cstdlib>
#include <string>
#include <atomic>

#include "recomp.h"
#include "librecomp/game.hpp"
#include "librecomp/overlays.hpp"
#include "librecomp/rsp.hpp"
#include "ultramodern/ultramodern.hpp"
#include "ultramodern/renderer_context.hpp"
#include "ultramodern/error_handling.hpp"

#include "r3ds.hpp"
#include "recomp_plan.h"

// Generated by tools/gen_section_table.py into game/, next to RecompiledFuncs.
extern FuncEntry section_funcs[];
extern SectionTableEntry section_table[];
extern const size_t num_sections;

// Generated by N64Recomp (RecompiledFuncs/funcs.h) and RSPRecomp (gen/aspMain.cpp).
void recomp_entrypoint(uint8_t* rdram, recomp_context* ctx);
extern "C" RspUcodeFunc aspMain;

namespace {

std::atomic<uint32_t> g_vi_count{0};
std::atomic<uint32_t> g_game_frames{0};
std::atomic<bool> g_game_started{false};
std::atomic<bool> g_game_exited{false};
char g_rom_path[128] = "";

// ---- ROM ------------------------------------------------------------------------------
const uint64_t kRomHash = recomp_plan::kRomHash;          // XXH3_64bits of the (U) [!] ROM
const std::u8string kGameId = u8"swe1racer";
const char* kRomCandidates[] = {
    "sdmc:/3ds/racer/baserom.z64",
    "sdmc:/3ds/racer/swe1racer.us.z64",
    "/3ds/racer/baserom.z64",
};

// ---- RSP ------------------------------------------------------------------------------
RspUcodeFunc* get_rsp_microcode(const OSTask* task) {
    // Graphics tasks go to the renderer; audio tasks run the recompiled aspMain microcode.
    if (task->t.type == M_AUDTASK) return &aspMain;
    return nullptr;   // the runtime hands graphics tasks to the renderer by itself
}

// ---- input ----------------------------------------------------------------------------
void poll_input() {
    hidScanInput();
}

bool get_input(int controller, uint16_t* buttons, float* x, float* y) {
    if (controller != 0) return false;       // Racer is 1-2 player; port 2 is not wired yet
    r3ds::input_poll();
    const r3ds::PadState pad = r3ds::input_get(0);
    *buttons = pad.buttons;
    *x = pad.x;
    *y = pad.y;
    return true;
}

void set_rumble(int controller, bool rumble) {
    // libctru has no rumble API for the console's own pad; the callback has to exist, and a
    // no-op is the correct behaviour here.
    (void)controller;
    (void)rumble;
}

ultramodern::input::connected_device_info_t get_connected_device_info(int controller) {
    ultramodern::input::connected_device_info_t info{};
    info.connected_device = controller == 0 ? ultramodern::input::Device::Controller
                                            : ultramodern::input::Device::None;
    info.connected_pak = ultramodern::input::Pak::None;
    return info;
}

// ---- audio ----------------------------------------------------------------------------
void queue_samples(int16_t* samples, size_t sample_count) {
    // sample_count is int16 samples; the ndsp sink wants frames (2 samples per frame).
    r3ds::audio_queue(samples, sample_count / 2);
}

size_t get_frames_remaining() {
    return r3ds::audio_frames_pending();
}

void set_frequency(uint32_t freq) {
    r3ds::audio_set_frequency(freq);
}

// ---- events / errors ------------------------------------------------------------------
void vi_callback() {
    g_vi_count.fetch_add(1);
}

void gfx_init_callback() {
    g_game_started.store(true);
}

void error_message_box(const char* msg) {
    r3ds::bootlog("runtime error: %s", msg);
    std::printf("runtime error: %s\n", msg);
}

std::string get_game_thread_name(const OSThread* t) {
    char buf[24];
    std::snprintf(buf, sizeof(buf), "n64_%u", t ? (unsigned)t->id : 0u);
    return buf;
}

// ---- entry ----------------------------------------------------------------------------
void game_thread(void*) {
    recomp::register_game([] {
        recomp::GameEntry e{};
        e.rom_hash = kRomHash;
        e.internal_name = recomp_plan::kRomInternalName;
        e.display_name = "Star Wars Episode I: Racer";
        e.game_id = kGameId;
        e.mod_game_id = "swe1racer";
        e.save_type = recomp::SaveType::Eep16k;   // Racer addresses 256 EEPROM blocks
        e.is_enabled = true;
        e.entrypoint_address = (gpr)(int32_t)recomp_plan::kEntrypointVram;
        e.entrypoint = recomp_entrypoint;
        return e;
    }());

    // Saves and settings live beside the ROM, not in the current directory.
    recomp::register_config_path("sdmc:/3ds/racer/");

    recomp::overlays::overlay_section_table_data_t sections{};
    sections.code_sections = section_table;
    sections.num_code_sections = num_sections;
    sections.total_num_sections = num_sections;
    recomp::overlays::overlays_by_index_t overlays{};
    overlays.table = nullptr;
    overlays.len = 0;
    recomp::overlays::register_overlays(sections, overlays);

    // The ROM the console already validated and converted (source/prepare.cpp).
    bool rom_ok = false;
    for (const char* path : kRomCandidates) {
        if (recomp::select_rom(path, kGameId) == recomp::RomValidationError::Good) {
            recomp::check_all_stored_roms();
            std::snprintf(g_rom_path, sizeof(g_rom_path), "%s", path);
            r3ds::bootlog("game: ROM accepted: %s", path);
            rom_ok = true;
            break;
        }
    }
    if (!rom_ok) {
        r3ds::bootlog("game: no usable ROM at sdmc:/3ds/racer/baserom.z64");
        g_game_exited.store(true);
        return;
    }

    recomp::Configuration cfg{};
    cfg.project_version = { 0, 3, 0 };
    cfg.window_handle = ultramodern::renderer::WindowHandle{};
    cfg.rsp_callbacks.get_rsp_microcode = get_rsp_microcode;
    cfg.renderer_callbacks.create_render_context = ultramodern::renderer::create_render_context;
    cfg.audio_callbacks.queue_samples = queue_samples;
    cfg.audio_callbacks.get_frames_remaining = get_frames_remaining;
    cfg.audio_callbacks.set_frequency = set_frequency;
    cfg.input_callbacks.poll_input = poll_input;
    cfg.input_callbacks.get_input = get_input;
    cfg.input_callbacks.set_rumble = set_rumble;
    cfg.input_callbacks.get_connected_device_info = get_connected_device_info;
    cfg.events_callbacks.vi_callback = vi_callback;
    cfg.events_callbacks.gfx_init_callback = gfx_init_callback;
    cfg.error_handling_callbacks.message_box = error_message_box;
    cfg.threads_callbacks.get_game_thread_name = get_game_thread_name;

    r3ds::bootlog("game: recomp::start (%d functions registered)", (int)num_sections);
    recomp::start(cfg);            // returns when the game exits
    r3ds::bootlog("game: recomp::start returned");
    g_game_exited.store(true);
}

} // namespace

namespace r3ds {

bool game_run() {
    static bool started = false;
    if (started) return true;
    started = true;

    // The runtime wants its own thread; main keeps the screens and the VI output alive.
    constexpr int kStack = 512 * 1024;
    s32 prio = 0x30;
    svcGetThreadPriority(&prio, CUR_THREAD_HANDLE);
    if (!threadCreate(game_thread, nullptr, kStack, prio, -1, false)) {
        bootlog("game: threadCreate failed");
        return false;
    }
    return true;
}

uint32_t game_vi_count() { return g_vi_count.load(); }
uint32_t game_frames() { return g_game_frames.load(); }
bool game_started() { return g_game_started.load(); }
bool game_exited() { return g_game_exited.load(); }
const char* game_rom_path() { return g_rom_path; }
void game_count_frame() { g_game_frames.fetch_add(1); }

} // namespace r3ds
