#!/usr/bin/env python3
"""Emit the section table N64ModernRuntime needs: function name -> VRAM offset -> size.

    tools/gen_section_table.py --symbols ../game-config/symbols.toml \
                               --out game/section_table.cpp

The names come from symbols.toml and must match the symbols in the generated
RecompiledFuncs/*.c (they do: N64Recomp uses the same names), which is why this is a
separate step from gen_recomp_plan.py (that one has no names, only addresses, because the
console does not need them).
"""
import argparse
import re

HEADER = '''// Generated by tools/gen_section_table.py - do not edit.
// Maps the recompiler's function names to VRAM offsets inside the main code section, which
// is what recomp::register_overlays() needs to translate a jump target into a function call.
#include "recomp.h"
#include "librecomp/sections.h"
#include "funcs.h"

'''


def parse(path):
    cur = None
    sections, funcs = [], []
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        if line == "[[section]]":
            cur = {}
            sections.append(cur)
        elif line == "[[section.functions]]":
            cur = {}
            funcs.append(cur)
        else:
            m = re.match(r'([A-Za-z_]+)\s*=\s*(.+)', line)
            if not m:
                continue
            key, val = m.group(1), m.group(2).strip().strip('"')
            if val.lower().startswith("0x"):
                val = int(val, 16)
            if cur is not None:
                cur[key] = val
    return sections, funcs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--funcs-header", default="",
                    help="funcs.h generated by N64Recomp; names not declared there are "
                         "resolved as <name>_recomp (libultra) or skipped")
    args = ap.parse_args()

    declared = set()
    if args.funcs_header:
        import re as _re
        for line in open(args.funcs_header, encoding="utf-8", errors="replace"):
            m = _re.search(r'void\s+([A-Za-z_][A-Za-z0-9_]*)', line)
            if m:
                declared.add(m.group(1))

    sections, funcs = parse(args.symbols)
    sec = sections[0]
    rom, vram = sec.get("rom", 0x1000), sec.get("vram", 0x80000400)
    out = [HEADER]
    out.append("static FuncEntry section_funcs[] = {")
    used = skipped = renamed = 0
    for f in funcs:
        if "name" not in f or "vram" not in f:
            continue
        name = f["name"]
        if not re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', name):
            continue
        if declared:
            # The generated code renames the libultra functions it reimplements
            # (osRecvMesg -> osRecvMesg_recomp); those whose names are absent entirely are
            # left out - the runtime provides them, so they are not part of the section.
            if name in declared:
                pass
            elif name + "_recomp" in declared:
                name = name + "_recomp"
                renamed += 1
            else:
                skipped += 1
                continue
        out.append("    { %s, 0x%X, 0x%X }," % (name, f["vram"] - vram, f.get("size", 0)))
        used += 1
    out.append("};")
    out.append("")
    out.append("SectionTableEntry section_table[] = {")
    out.append("    { 0x%X, 0x%X, 0x%X, section_funcs, ARRLEN(section_funcs), nullptr, 0, 0 },"
               % (rom, vram, sec.get("size", 0x98000)))
    out.append("};")
    out.append("const size_t num_sections = ARRLEN(section_table);")
    open(args.out, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("%s: %d functions (%d renamed to *_recomp, %d skipped: provided by the runtime)"
          % (args.out, used, renamed, skipped))


if __name__ == "__main__":
    main()
