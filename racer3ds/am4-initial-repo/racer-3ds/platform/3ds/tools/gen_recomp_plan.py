#!/usr/bin/env python3
"""Turn the project's symbols.toml into a header the console can compile in.

The recompiler itself runs on a PC (see recompile.sh), but the *plan* it works from - which
function starts where, inside which ROM section - is just data, and having it on the console
is what lets the app validate a ROM against it before anyone tries to build.

    tools/gen_recomp_plan.py --symbols ../game-config/symbols.toml \
                             --out       include/recomp_plan.h

Regenerate whenever symbols.toml changes.
"""
import argparse
import re


def parse(path):
    text = open(path, encoding="utf-8").read()
    sections, current = [], None
    funcs = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        if line == "[[section]]":
            current = {}
            sections.append(current)
            continue
        if line == "[[section.functions]]":
            funcs.append({})
            continue
        m = re.match(r'([A-Za-z_]+)\s*=\s*(.+)', line)
        if not m:
            continue
        key, val = m.group(1), m.group(2).strip()
        if key == "name":
            val = val.strip('"')
        elif val.lower().startswith("0x"):
            val = int(val, 16)
        target = funcs[-1] if funcs and key in ("name", "vram", "size") and current is not None \
            and len(funcs) > 0 and "vram" not in funcs[-1] or (funcs and key in ("name",)) else current
        # functions come after `[[section.functions]]`; a plain key belongs to whichever block
        # was opened last.
        if funcs and (line.startswith("name") or line.startswith("vram") or line.startswith("size")):
            target = funcs[-1]
        elif current is not None and key in ("name", "rom", "vram", "size") and (not funcs or
                line.startswith("rom")):
            target = current
        target[key] = val
    return sections, funcs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--crc1", type=lambda s: int(s, 0), default=0x72F70398)
    ap.add_argument("--crc2", type=lambda s: int(s, 0), default=0x6556A98B)
    args = ap.parse_args()

    sections, funcs = parse(args.symbols)
    if not sections:
        raise SystemExit("no [[section]] in %s" % args.symbols)
    code = sections[0]
    out = []
    out.append("// Generated by tools/gen_recomp_plan.py from symbols.toml - do not edit.")
    out.append("//")
    out.append("// The function map the N64Recomp build uses, in a form the console can check a ROM")
    out.append("// against. One entry per function: ROM-relative VRAM, size in bytes.")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace recomp_plan {")
    out.append("")
    out.append("struct Section {")
    out.append("    uint32_t rom;   // file offset of the section")
    out.append("    uint32_t vram;  // VRAM the section loads at")
    out.append("    uint32_t size;")
    out.append("};")
    out.append("")
    out.append("constexpr Section kCodeSection = { 0x%X, 0x%X, 0x%X };" % (
        code.get("rom", 0x1000), code.get("vram", 0x80000400), code.get("size", 0x98000)))
    out.append("constexpr uint32_t kEntrypointVram = 0x80000400;")
    out.append("constexpr uint32_t kExpectedCrc1 = 0x%08X;" % args.crc1)
    out.append("constexpr uint32_t kExpectedCrc2 = 0x%08X;" % args.crc2)
    out.append("constexpr const char* kRomInternalName = \"STAR WARS EP1 RACER\";")
    out.append("// XXH3_64bits of baserom.z64, as registered with recomp::register_game().")
    out.append("constexpr uint64_t kRomHash = 0x9B89D0F9EBC12D32ULL;")
    out.append("")
    out.append("struct Func { uint32_t vram; uint32_t size; };")
    out.append("")
    out.append("constexpr Func kFuncs[] = {")
    for f in funcs:
        if "vram" not in f:
            continue
        out.append("    { 0x%08X, 0x%X }," % (f["vram"], f.get("size", 0)))
    out.append("};")
    out.append("constexpr int kFuncCount = (int)(sizeof(kFuncs) / sizeof(kFuncs[0]));")
    out.append("")
    out.append("} // namespace recomp_plan")
    open(args.out, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("%s: %d functions, code section rom 0x%X vram 0x%X size 0x%X" % (
        args.out, len(funcs), code.get("rom", 0), code.get("vram", 0), code.get("size", 0)))


if __name__ == "__main__":
    main()
