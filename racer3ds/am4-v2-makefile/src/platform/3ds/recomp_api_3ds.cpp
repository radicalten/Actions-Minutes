// Star Wars Episode I: Racer - game-specific host functions for the 3DS.
//
// These are the host-side pieces the recompiled game calls into. They are
// direct ports of the desktop frontend's src/main.cpp, with the Windows-only
// crash handler and the per-frame diagnostic logging removed. The memory
// layout constants (PI handle, VI state, sink queue, osMemSize) are the
// game's own RDRAM addresses and must stay in lock-step with symbols.toml.
#include <cstdio>
#include <cstring>
#include <string>

#include "recomp.h"
#include "librecomp/sections.h"
#include "librecomp/overlays.hpp"
#include "librecomp/addresses.hpp"
#include "librecomp/game.hpp"
#include "ultramodern/ultramodern.hpp"
#include "ultramodern/ultra64.h"

// Generated by tools/3ds/recompile.sh (gen_lookup_table.py):
// section_table[] / num_sections describe the single static code section.
extern SectionTableEntry section_table[];
extern const size_t num_sections;

namespace {

// Big-endian native-order word write into guest RDRAM. The recompiled MEM_W
// accessor reads uint32 words straight back, so this lands the bytes exactly
// as the guest's word stores would (sub-word accesses use the XOR swaps).
void write32(uint8_t* rdram, uint32_t mips_addr, uint32_t value) {
    *reinterpret_cast<uint32_t*>(rdram + (mips_addr - 0x80000000u)) = value;
}

}  // namespace

// ---------------------------------------------------------------------------
// Section registration
// ---------------------------------------------------------------------------
// Racer is a single static section (no overlays): the index table is empty,
// exactly as the desktop's register_overlays call sets it up.
void register_racer_overlays() {
    recomp::overlays::overlay_section_table_data_t sections{};
    sections.code_sections = section_table;
    sections.num_code_sections = num_sections;
    sections.total_num_sections = num_sections;

    recomp::overlays::overlays_by_index_t overlays{};
    overlays.table = nullptr;
    overlays.len = 0;

    recomp::overlays::register_overlays(sections, overlays);
    printf("[racer] registered %zu section(s), %zu function(s)\n",
           num_sections, section_table[0].num_funcs);
}

// ---------------------------------------------------------------------------
// SI DMA: the game's __osSiRawStartDma is COP0/MMIO based and can't be
// recompiled. It moves a 64-byte block between DRAM and PIF RAM and raises an
// SI interrupt on completion.
//
//   a0 (r4) = direction (1 = DRAM->PIF write, 0 = PIF->DRAM read)
//   a1 (r5) = DRAM buffer address
//
// There is no PIF hardware on the host. On a read we synthesize the controller
// status block the game's detection code (func_800899E8) expects: 8 bytes per
// channel, 4 channels. Controller 0 is present (standard pad, no pak); channels
// 1-3 report "no controller" through the error bits in byte 2. The runtime's
// HID layer owns the actual pad state, read through osCont* afterwards.
// ---------------------------------------------------------------------------
extern "C" void __osSiRawStartDma_recomp(uint8_t* rdram, recomp_context* ctx) {
    const int32_t dir = static_cast<int32_t>(ctx->r4);
    const uint32_t buf = static_cast<uint32_t>(ctx->r5);

    if (dir == 0 && buf != 0) {
        for (int ch = 0; ch < 4; ch++) {
            const uint32_t c = buf + static_cast<uint32_t>(ch) * 8u;
            if (ch == 0) {
                write32(rdram, c + 0, 0xFF010300u);  // pad, tx=1, rx=3 (no error), cmd=0
                write32(rdram, c + 4, 0x050000FFu);  // type=0x0005 (standard pad), no pak
            } else {
                write32(rdram, c + 0, 0xFF018300u);  // byte2=0x83 -> error bit set
                write32(rdram, c + 4, 0xFFFFFFFFu);  // no controller on this channel
            }
        }
    }
    // Writes (controller commands) carry nothing the host must answer.

    // No real hardware to wait on: signal SI completion immediately.
    ultramodern::send_si_message();
    ctx->r2 = 0;  // success
}

// The game's osGetCount (racer_osGetCount, redirected by post_recomp_patches.py).
// The mfc0 instruction sign-extends, so cast the runtime count to int32.
extern "C" void racer_get_count(uint8_t* /*rdram*/, recomp_context* ctx) {
    ctx->r2 = static_cast<int32_t>(osGetCount());
}

// ---------------------------------------------------------------------------
// Game init: replicate the libultra boot state the stubbed COP0 code skips.
// Ported verbatim in substance from the desktop frontend's on_game_init.
// ---------------------------------------------------------------------------
void racer_on_game_init(uint8_t* rdram, recomp_context* /*ctx*/) {
    // The game's boot code at 0x8008D284 initializes the PI (cartridge ROM)
    // handle and stores it at globals 0x800A7BC0 and 0x800A7FC0. That code is
    // stubbed because it contains COP0 instructions; build the handle here.
    const int32_t handle_addr = recomp::cart_handle;  // 0x80800000
    auto* handle = reinterpret_cast<OSPiHandle*>(
        rdram + (static_cast<uint32_t>(handle_addr) - 0x80000000u));
    std::memset(handle, 0, sizeof(OSPiHandle));
    handle->type = 0;                     // PI_DOMAIN2 (cartridge)
    handle->baseAddress = 0xB0000000;    // phys_to_k1(0x10000000): cartridge ROM base
    handle->domain = 0;

    // 0x800A7BC0 = __osCartRomHandle, 0x800A7FC0 = __osPiTable (device list head).
    write32(rdram, 0x800A7BC0, static_cast<uint32_t>(handle_addr));
    write32(rdram, 0x800A7FC0, static_cast<uint32_t>(handle_addr));
    // Self-link the handle's next pointer (a list of one element).
    write32(rdram, static_cast<uint32_t>(handle_addr),
            static_cast<uint32_t>(handle_addr));

    // VI state for the scheduler thread (func_8008BC30 -> static_0_800941D0):
    // it reads a "current VI mode" pointer from 0x800A7F50 and uses its
    // retrace count (+0x02 halfword) and response queue (+0x10). osCreateViManager
    // is stubbed, so synthesize the state in unused BSS at 0x800A7F00 with a
    // sink queue at 0x800A7E80 that absorbs the scheduler's frame messages.
    //
    // OSMesgQueue (big-endian): the last two words are msgCount (8) and the
    // buffer pointer (0x800A7E60); the queue starts zeroed.
    write32(rdram, 0x800A7E80 + 0x00, 0);
    write32(rdram, 0x800A7E80 + 0x04, 0);
    write32(rdram, 0x800A7E80 + 0x08, 0);
    write32(rdram, 0x800A7E80 + 0x0C, 0);
    write32(rdram, 0x800A7E80 + 0x10, 8);
    write32(rdram, 0x800A7E80 + 0x14, 0x800A7E60);

    // Fake VI state: the word at +0x00's lower halfword is the +0x02 retrace
    // count (1), the word at +0x10 holds the response (sink) queue.
    std::memset(rdram + (0x800A7F00 - 0x80000000u), 0, 0x20);
    write32(rdram, 0x800A7F00, 0x00000001);
    write32(rdram, 0x800A7F10, 0x800A7E80);
    write32(rdram, 0x800A7F50, 0x800A7F00);

    // osMemSize at 0x80000318: IPL3 normally writes the detected RDRAM size,
    // but IPL3 is stubbed. Racer requires the Expansion Pak: report 8 MB.
    // 0x318 is below the game's BSS clear (0x520+), so this survives. The
    // framebuffer pointer table at 0x80114530 must not be seeded here: it is
    // inside the cleared range and populated by func_80039A38 itself.
    write32(rdram, 0x80000318, 0x00800000);

    printf("[racer] boot state installed: PI handle 0x%08X, VI state 0x800A7F00, osMemSize 8 MB\n",
           static_cast<uint32_t>(handle_addr));
}

// Human-readable names for the game's threads in the runtime's diagnostics.
std::string racer_game_thread_name(const OSThread* /*t*/) {
    return "SWE1R-Thread";
}
