// Star Wars Episode I: Racer - Nintendo 3DS entry point.
//
// Everything the rt64-3ds runtime needs to know about this game lives in the
// GameDesc below: how to recognize the ROM, which recompiled functions to
// call, how the RSP tasks and the renderer are wired, and how audio runs.
// The desktop frontend's RT64Context is not ported: its contract (F3DEX_GBI_2
// display lists, ucode pointers masked to physical RDRAM, the VI width read
// from the game's VI registers) becomes RenderDesc + runtime behavior here.
#include <cstdio>
#include <string>

#include "recomp3ds.h"
#include "librecomp/rsp.hpp"
#include "librecomp/overlays.hpp"
#include "librecomp/game.hpp"
#include "ultramodern/ultra64.h"

// Generated by N64Recomp (recomp.toml entrypoint 0x80000400).
extern "C" void recomp_entrypoint(uint8_t* rdram, recomp_context* ctx);

// Generated by RSPRecomp (rsp/aspMain.toml): the stock libultra aspMain audio
// microcode, recompiled to C++. Graphics tasks never reach the RSP callback:
// the runtime routes M_GFXTASK straight to the PICA renderer.
extern RspUcodeFunc aspMain;

// recomp_api_3ds.cpp
void register_racer_overlays();
void racer_on_game_init(uint8_t* rdram, recomp_context* ctx);
std::string racer_game_thread_name(const OSThread* t);

namespace {

// Racer's copy of aspMain is the stock libultra ABI 1 audio microcode (the
// same build Pokemon Snap uses), so audio tasks return the recompiled
// aspMain; with GameDesc::audio_hle the runtime swaps it for the aspmain_hle
// CPU interpreter (see desc below). Anything that is not an audio task has
// already been claimed by the renderer, so nullptr matches the sibling ports.
RspUcodeFunc* get_rsp_microcode(const OSTask* task) {
    if (task->t.type == M_AUDTASK) {
        return aspMain;
    }
    return nullptr;
}

}  // namespace

int main(int argc, char** argv) {
    (void)argc;
    (void)argv;

    recomp3ds::GameDesc desc{};

    // sdmc:/3ds/racer/baserom.z64, plus saves and settings.ini beside it.
    desc.game_id = u8"swe1racer";
    desc.sd_dir = "racer";
    desc.project_version = recomp::Version{ 0, 3, 0 };

    desc.entry = recomp::GameEntry{
        .rom_hash = 0x9B89D0F9EBC12D32ULL,        // XXH3_64bits of the US baserom (NEPE, CRC1 0x72F70398)
        .internal_name = "STAR WARS EP1 RACER",
        .display_name = "Star Wars Episode I: Racer",
        .game_id = u8"swe1racer",
        .mod_game_id = "swe1racer",
        .save_type = recomp::SaveType::Eep16k,     // 256 EEPROM blocks, saves at 0 and 0x400
        .thumbnail_bytes = {},
        .is_enabled = true,
        .decompression_routine = nullptr,          // no compressed code in this title
        .has_compressed_code = false,
        .entrypoint_address = (gpr)(int32_t)0x80000400,
        .entrypoint = recomp_entrypoint,
        .thread_create_callback = nullptr,
        .on_init_callback = racer_on_game_init,
    };
    // The user places the ROM as sdmc:/3ds/racer/baserom.z64 (game_id stays
    // "swe1racer" for save/settings identity).
    desc.entry.rom_filename_override = u8"baserom.z64";

    desc.rsp.get_rsp_microcode = get_rsp_microcode;
    desc.register_overlays = register_racer_overlays;
    desc.register_patches = nullptr;               // Racer has no RecompiledPatches
    desc.get_game_thread_name = racer_game_thread_name;

    // ---- Renderer ---------------------------------------------------------
    // Racer's GSP microcode is F3DEX_GBI_2 (confirmed against the game's
    // display-list setup), so the F3DEX2 interpreter is the correct one.
    // The game's VI output is the standard N64 320x240 frame.
    desc.render.game_name = "Star Wars Episode I: Racer";
    desc.render.gbi = rt64_3ds::Gbi::F3DEX2;
    desc.render.vi_width = 320;
    desc.render.vi_height = 240;
    // The desktop frontend enables RT64's force-BranchLessZ (always the near
    // LOD model); that is the library default, stated here for clarity.
    desc.render.force_lod_branch = true;
    desc.render.cull_dl = true;
    // No gEXMatrixGroup transform tagging exists in Racer, so frame
    // interpolation and the stereo projection machinery stay at their safe
    // defaults (unclassified perspective draws are not reprojected).
    desc.render.frame_interpolation = false;
    // Old 3DS GPU savings used by the sibling ports, each picture-identical:
    // 16-bit eye depth, I/IA textures as LA8, and the frame's leading
    // full-screen fill turned into the eye clear (Racer opens every frame
    // with one and has no alpha need for it).
    desc.render.eye_depth16 = true;
    desc.render.intensity_textures16 = true;
    desc.render.fill_clear = true;

    // ---- Audio ------------------------------------------------------------
    // Interpret the stock ABI 1 aspMain on the CPU instead of running the
    // recompiled microcode: on an Old 3DS the vector microcode emulation is
    // the slower path for this ucode, and aspmain_hle matches Goemon's.
    // settings.ini's dbg_audio_rsp=1 runs the recompiled aspMain instead, for
    // A/B comparison if a ucode revision ever disagrees with the interpreter.
    desc.audio_hle = true;
    desc.audio_hle_family = recomp3ds::AudioHle::Aspmain;
    // Racer drives an SDK-style libultra audio manager whose next task waits
    // on the previous one's completion: report completion immediately and
    // hand over the samples when the task has really run (async audio tasks),
    // keeping four frames of margin so the DSP cannot run dry between buffers.
    desc.audio_async = true;
    desc.audio_margin_frames = 4;

    // ---- Scheduling and memory -------------------------------------------
    // Two cores on an Old 3DS: the game owns core 0, the renderer and audio
    // share core 1's 80% - the layout every sibling game settles on.
    desc.two_cores_game_on_core0 = true;
    // The 32 MB cartridge cannot sit beside the 16 MB RDRAM model in an Old
    // 3DS application heap, so stream it from the SD card with the default
    // cache. A New 3DS decides from the room it actually has.
    desc.rom_new3ds = recomp3ds::GameDesc::RomPlace::Auto;
    desc.rom_old3ds = recomp3ds::GameDesc::RomPlace::Stream;
    // No frame interpolation: offer the game's own rate on an Old 3DS rather
    // than capping to 30 fps; settings.ini may still choose otherwise.
    desc.old3ds_frame_cap = 0;

    // Input uses the library's default mapping (A/B, Y or ZL for Z, R or ZR,
    // X for C-Up, Start, D-pad, Circle Pad stick, C-Stick C buttons), which is
    // fully playable on an Old 3DS. desc.button_map stays null to select it.

#ifdef RACER_NULL_RENDERER
    // Bring-up build: accept and parse display lists, draw nothing.
    desc.null_renderer = true;
#endif

    return recomp3ds::run(desc);
}
